#!/usr/bin/env python3
"""SIVO-Remotion Phase 2 — meme library generator.

Generates ~10 looping meme MP4s (1080x1920, 2s @ 30fps) into public/memes/.
ALL artwork is ORIGINAL: drawn with PIL shapes (circles, polygons, lines)
by this script. No Tenor/Giphy/copyrighted GIFs, no third-party images,
no text. Every motion is cyclic (sin or modulo wrap) so the 2s loop is
seamless under Remotion's <Loop>.

Each meme is a generic visual concept, not a copy of any known meme:
  pain-01    red arrow falling (problem / losses)
  pain-02    leaky bucket (losing money)
  pain-03    spinning clock (time pressure)
  solution-01 lightbulb pulsing (idea)
  solution-02 green arrow rising (growth)
  workflow-01 two gears turning (process)
  workflow-02 checklist checks cycling (steps)
  benefits-01 coins dropping into a piggy bank (savings)
  outro-01   rocket rising with stars (ship / success)
  outro-02   trophy with twinkling stars (win)

License: original artwork generated by SIVO code — no license
restrictions. See MEMES.md for the per-meme record.

Usage: python3 scripts/make_memes.py
"""
import math
import os
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw

W, H = 1080, 1920
FRAMES = 60  # 2s @ 30fps
BG = (10, 10, 10)
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "public", "memes")

RED = (239, 68, 68)
GREEN = (88, 214, 141)
BLUE = (88, 166, 255)
YELLOW = (250, 204, 21)
ORANGE = (255, 107, 53)
WHITE = (255, 255, 255)
GRAY = (156, 163, 175)
GOLD = (250, 204, 21)


def new_frame():
    return Image.new("RGB", (W, H), BG)


def star_points(cx, cy, r_out, r_in, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        r = r_out if i % 2 == 0 else r_in
        a = math.radians(rot + i * 180 / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def draw_arrow_falling(d, p, color):
    # Static descending zigzag + two arrows falling with wrap.
    d.line([(140, 500), (380, 800), (560, 700), (820, 1100), (940, 1000)],
           fill=color, width=14)
    for off in (0.0, 0.5):
        q = (p + off) % 1.0
        y = 350 + q * 1300
        x = 540
        d.polygon([(x, y + 110), (x - 70, y), (x - 22, y),
                   (x - 22, y - 110), (x + 22, y - 110), (x + 22, y),
                   (x + 70, y)], fill=color)


def draw_arrow_rising(d, p, color):
    # Static ascending zigzag + two arrows rising with wrap.
    d.line([(140, 1400), (380, 1100), (560, 1200), (820, 800), (940, 900)],
           fill=color, width=14)
    for off in (0.0, 0.5):
        q = (p + off) % 1.0
        y = 1600 - q * 1300
        x = 540
        d.polygon([(x, y - 110), (x - 70, y), (x - 22, y),
                   (x - 22, y + 110), (x + 22, y + 110), (x + 22, y),
                   (x + 70, y)], fill=color)


def pain_01(d, p):
    draw_arrow_falling(d, p, RED)


def pain_02(d, p):
    # Bucket (trapezoid outline) + oscillating water + falling drips.
    d.polygon([(330, 800), (750, 800), (700, 1350), (380, 1350)],
              outline=WHITE, width=12)
    wy = 1050 + 40 * math.sin(2 * math.pi * p)
    d.line([(360, wy), (720, wy)], fill=BLUE, width=10)
    for k, x in enumerate((450, 540, 630)):
        y = 1350 + ((p * 500 + k * 170) % 500)
        d.ellipse([x - 16, y - 26, x + 16, y + 26], fill=BLUE)


def pain_03(d, p):
    cx, cy, r = 540, 960, 380
    d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=RED, width=16)
    for i in range(12):
        a = math.radians(i * 30)
        x1 = cx + (r - 30) * math.cos(a)
        y1 = cy + (r - 30) * math.sin(a)
        x2 = cx + (r - 70) * math.cos(a)
        y2 = cy + (r - 70) * math.sin(a)
        d.line([(x1, y1), (x2, y2)], fill=WHITE, width=10)
    a = 2 * math.pi * p - math.pi / 2
    d.line([(cx, cy), (cx + (r - 90) * math.cos(a),
                       cy + (r - 90) * math.sin(a))], fill=RED, width=18)
    d.ellipse([cx - 28, cy - 28, cx + 28, cy + 28], fill=WHITE)


def solution_01(d, p):
    # Bulb: circle + base; rays pulse with phase offsets (seamless).
    cx, cy, r = 540, 820, 260
    glow = int(60 + 40 * math.sin(2 * math.pi * p))
    d.ellipse([cx - r - 60, cy - r - 60, cx + r + 60, cy + r + 60],
              outline=(glow, glow, 0), width=8)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=YELLOW, width=16)
    for i in range(8):
        a = math.radians(i * 45 - 90)
        pulse = 0.5 + 0.5 * math.sin(2 * math.pi * p + i * math.pi / 4)
        r1 = r + 50
        r2 = r + 50 + 40 + 60 * pulse
        d.line([(cx + r1 * math.cos(a), cy + r1 * math.sin(a)),
                (cx + r2 * math.cos(a), cy + r2 * math.sin(a))],
               fill=YELLOW, width=12)
    d.rectangle([cx - 110, cy + r + 20, cx + 110, cy + r + 200],
                outline=YELLOW, width=14)
    d.line([(cx - 110, cy + r + 90), (cx + 110, cy + r + 90)],
           fill=YELLOW, width=10)
    d.line([(cx - 110, cy + r + 140), (cx + 110, cy + r + 140)],
           fill=YELLOW, width=10)


def solution_02(d, p):
    draw_arrow_rising(d, p, GREEN)


def workflow_01(d, p):
    def gear(cx, cy, r, phase, color):
        for i in range(8):
            a = 2 * math.pi * p * phase + math.radians(i * 45)
            x1 = cx + (r - 10) * math.cos(a)
            y1 = cy + (r - 10) * math.sin(a)
            x2 = cx + (r + 55) * math.cos(a)
            y2 = cy + (r + 55) * math.sin(a)
            d.line([(x1, y1), (x2, y2)], fill=color, width=26)
        d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=color, width=16)
        d.ellipse([cx - 60, cy - 60, cx + 60, cy + 60], outline=color, width=12)
    gear(400, 800, 220, 1, BLUE)
    gear(690, 1180, 170, -1, GRAY)


def workflow_02(d, p):
    for i, y in enumerate((600, 950, 1300)):
        d.rectangle([200, y, 320, y + 120], outline=WHITE, width=10)
        d.rectangle([380, y + 30, 880, y + 90], outline=GRAY, width=8)
        # Checkmark grows/fades in sequence (phase offsets, seamless).
        a = 0.5 + 0.5 * math.sin(2 * math.pi * p - i * 2 * math.pi / 3)
        if a > 0.15:
            w = max(6, int(14 * a))
            d.line([(225, y + 60), (265, y + 100)], fill=GREEN, width=w)
            d.line([(265, y + 100), (305, y + 25)], fill=GREEN, width=w)


def benefits_01(d, p):
    # Piggy bank: ellipse body + snout + ear + legs; coins fall with wrap.
    bob = 12 * math.sin(2 * math.pi * p)
    bx, by = 540, 1050 + bob
    d.ellipse([bx - 300, by - 180, bx + 300, by + 180], outline=YELLOW, width=14)
    d.ellipse([bx + 210, by - 60, bx + 330, by + 60], outline=YELLOW, width=12)
    d.polygon([(bx - 180, by - 170), (bx - 120, by - 280), (bx - 60, by - 170)],
              outline=YELLOW, width=12)
    for lx in (bx - 200, bx + 160):
        d.line([(lx, by + 160), (lx, by + 260)], fill=YELLOW, width=14)
    d.rectangle([bx - 40, by - 190, bx + 40, by - 160], fill=BG)
    for k in range(3):
        y = 250 + ((p * 700 + k * 260) % 700)
        d.ellipse([bx - 45, y - 45, bx + 45, y + 45], fill=GOLD)
        d.ellipse([bx - 45, y - 45, bx + 45, y + 45], outline=WHITE, width=6)


def outro_01(d, p):
    # Stars stream down (wrap) + rocket bobs + flame flickers (4x/loop).
    for k in range(24):
        x = (k * 173) % W
        y = (k * 331 + p * 700) % H
        r = 4 + (k % 3) * 3
        d.ellipse([x - r, y - r, x + r, y + r], fill=WHITE)
    bob = 20 * math.sin(2 * math.pi * p)
    cx, cy = 540, 960 + bob
    flame = 130 + 60 * math.sin(2 * math.pi * 4 * p)
    d.polygon([(cx - 55, cy + 230), (cx + 55, cy + 230), (cx, cy + 230 + flame)],
              fill=ORANGE)
    d.polygon([(cx, cy - 360), (cx + 130, cy + 60),
               (cx + 130, cy + 230), (cx - 130, cy + 230),
               (cx - 130, cy + 60)], fill=WHITE)
    d.polygon([(cx - 130, cy + 60), (cx - 220, cy + 230), (cx - 130, cy + 230)],
              fill=RED)
    d.polygon([(cx + 130, cy + 60), (cx + 220, cy + 230), (cx + 130, cy + 230)],
              fill=RED)
    d.ellipse([cx - 55, cy - 80, cx + 55, cy + 30], outline=BLUE, width=10)


def outro_02(d, p):
    # Trophy: cup + handles + stem + base; stars twinkle with phase offsets.
    cx, cy = 540, 820
    d.polygon([(cx - 190, cy - 320), (cx + 190, cy - 320),
               (cx + 150, cy + 60), (cx - 150, cy + 60)], outline=GOLD, width=16)
    d.arc([cx - 330, cy - 280, cx - 120, cy + 40], 90, 270, fill=GOLD, width=14)
    d.arc([cx + 120, cy - 280, cx + 330, cy + 40], 90, 270, fill=GOLD, width=14)
    d.rectangle([cx - 35, cy + 60, cx + 35, cy + 220], outline=GOLD, width=14)
    d.polygon([(cx - 170, cy + 220), (cx + 170, cy + 220),
               (cx + 210, cy + 340), (cx - 210, cy + 340)], outline=GOLD, width=14)
    for i, (sx, sy) in enumerate(((220, 420), (860, 420), (180, 1250),
                                   (900, 1250), (540, 1500))):
        tw = 0.5 + 0.5 * math.sin(2 * math.pi * p + i * 2 * math.pi / 5)
        r = 22 + 26 * tw
        d.polygon(star_points(sx, sy, r, r * 0.45), fill=YELLOW)


MEMES = {
    "pain-01": (pain_01, "Red arrow falling + descending zigzag — problem / losses"),
    "pain-02": (pain_02, "Leaky bucket, water oscillating, drips falling — losing money"),
    "pain-03": (pain_03, "Clock with a fast-spinning red hand — time pressure"),
    "solution-01": (solution_01, "Lightbulb with pulsing rays — an idea"),
    "solution-02": (solution_02, "Green arrow rising + ascending zigzag — growth"),
    "workflow-01": (workflow_01, "Two gears turning opposite directions — process"),
    "workflow-02": (workflow_02, "Checklist, checkmarks cycling in sequence — steps"),
    "benefits-01": (benefits_01, "Coins dropping into a piggy bank — savings"),
    "outro-01": (outro_01, "Rocket rising, stars streaming, flame flickering — ship / success"),
    "outro-02": (outro_02, "Trophy with twinkling stars — a win"),
}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, (draw, _desc) in MEMES.items():
        out_path = os.path.join(OUT_DIR, f"{name}.mp4")
        with tempfile.TemporaryDirectory() as tmp:
            for f in range(FRAMES):
                img = new_frame()
                draw(ImageDraw.Draw(img), f / FRAMES)
                img.save(os.path.join(tmp, f"frame_{f:03d}.png"))
            cmd = ["ffmpeg", "-y", "-v", "error", "-framerate", "30",
                   "-i", os.path.join(tmp, "frame_%03d.png"),
                   "-c:v", "libx264", "-pix_fmt", "yuv420p", "-an", out_path]
            subprocess.run(cmd, check=True)
        print(f"meme -> {out_path}")
    print(f"Done: {len(MEMES)} memes in {OUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
